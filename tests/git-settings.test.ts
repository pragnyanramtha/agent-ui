import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { afterAll, afterEach, beforeAll, beforeEach, describe, expect, it } from "vitest";

/* The server reads Settings > Git from the synced settings file: background fetch, which agent writes commit
 * messages and in what style. */

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "agentu-gitsettings-"));
process.env.AGENT_U_SETTINGS = path.join(tmp, "settings.json");
process.env.XDG_CACHE_HOME = path.join(tmp, "cache");
const remote = path.join(tmp, "remote.git");
const repo = path.join(tmp, "repo");
const bin = path.join(tmp, "bin");
const logs = path.join(tmp, "logs");
const NONE = "/nonexistent/agent-u-test-bin";
const ENV = { ...process.env, GIT_AUTHOR_NAME: "t", GIT_AUTHOR_EMAIL: "t@t", GIT_COMMITTER_NAME: "t", GIT_COMMITTER_EMAIL: "t@t" };
const sh = (args: string[], cwd = repo) => execFileSync("git", args, { cwd, encoding: "utf8", env: ENV, stdio: "pipe" });
const fake = (name: string, script: string) => fs.writeFileSync(path.join(bin, name), `#!/bin/sh\n${script}\n`, { mode: 0o755 });
const saved = { PATH: process.env.PATH, CLAUDE_BIN: process.env.CLAUDE_BIN, CODEX_BIN: process.env.CODEX_BIN, GEMINI_BIN: process.env.GEMINI_BIN, GIT_FETCH_INTERVAL_MS: process.env.GIT_FETCH_INTERVAL_MS };

let g: typeof import("@/lib/server/git");
let settings: typeof import("@/lib/server/settings");

const agentsFrom = (...names: string[]) => {
  process.env.PATH = `${bin}${path.delimiter}${saved.PATH ?? ""}`;
  for (const [agent, env] of [["claude", "CLAUDE_BIN"], ["codex", "CODEX_BIN"], ["gemini", "GEMINI_BIN"]] as const) {
    if (names.includes(agent)) delete process.env[env];
    else process.env[env] = NONE;
  }
};
const store = (patch: Record<string, unknown>) => {
  const r = settings.updateSynced(patch);
  if (!r.ok) throw new Error(r.errors.join(" "));
};

beforeAll(async () => {
  g = await import("@/lib/server/git");
  settings = await import("@/lib/server/settings");
  fs.mkdirSync(bin);
  fs.mkdirSync(logs);
  execFileSync("git", ["init", "-q", "--bare", "-b", "main", remote]);
  execFileSync("git", ["clone", "-q", remote, repo], { env: ENV, stdio: "pipe" });
  sh(["checkout", "-q", "-b", "main"]);
  fs.writeFileSync(path.join(repo, "a.txt"), "one\n");
  sh(["add", "-A"]);
  sh(["commit", "-qm", "Add the first file"]);
  sh(["push", "-q", "-u", "origin", "main"]);
});
beforeEach(() => fs.rmSync(settings.SETTINGS_PATH, { force: true }));
afterEach(() => {
  for (const [k, v] of Object.entries(saved)) {
    if (v === undefined) delete process.env[k];
    else process.env[k] = v;
  }
  for (const f of fs.readdirSync(bin)) fs.rmSync(path.join(bin, f));
  for (const f of fs.readdirSync(logs)) fs.rmSync(path.join(logs, f));
});
afterAll(() => fs.rmSync(tmp, { recursive: true, force: true }));

describe("background fetch interval", () => {
  it("falls back to GIT_FETCH_INTERVAL_MS, then a minute, until someone picks one", () => {
    delete process.env.GIT_FETCH_INTERVAL_MS;
    expect(g.fetchIntervalMs()).toBe(60_000);
    process.env.GIT_FETCH_INTERVAL_MS = "300000";
    expect(g.fetchIntervalMs()).toBe(300_000);
    process.env.GIT_FETCH_INTERVAL_MS = "0";
    expect(g.fetchIntervalMs()).toBe(0);
    process.env.GIT_FETCH_INTERVAL_MS = "soon";
    expect(g.fetchIntervalMs()).toBe(60_000);
  });

  it("follows the synced setting over the environment, and goes back to it on reset", () => {
    process.env.GIT_FETCH_INTERVAL_MS = "300000";
    store({ gitFetchInterval: "15" });
    expect(g.fetchIntervalMs()).toBe(15 * 60_000);
    store({ gitFetchInterval: "off" });
    expect(g.fetchIntervalMs()).toBe(0);
    store({ gitFetchInterval: "1" });
    expect(g.fetchIntervalMs()).toBe(60_000);
    store({ gitFetchInterval: null });
    expect(g.fetchIntervalMs()).toBe(300_000);
  });

  it("doesn't fetch while it's off, and does once it's back on", async () => {
    const dir = path.join(tmp, "fetch-off");
    execFileSync("git", ["clone", "-q", remote, dir], { env: ENV, stdio: "pipe" });
    store({ gitFetchInterval: "off" });
    await g.autoFetch(dir);
    expect((await g.status(dir))?.fetchedAt).toBeNull();
    store({ gitFetchInterval: "5" });
    await g.autoFetch(dir);
    expect((await g.status(dir))?.fetchedAt).toBeGreaterThan(0);
  });
});

describe("commit message settings", () => {
  it("maps Generated by to the agents asked", () => {
    expect(g.messageAgents("auto")).toEqual(["claude", "codex", "gemini"]);
    expect(g.messageAgents("codex")).toEqual(["codex"]);
    expect(g.messageAgents("off")).toEqual([]);
    expect(g.messageAgents()).toEqual(["claude", "codex", "gemini"]);
    store({ commitMessageAgent: "gemini" });
    expect(g.messageAgents()).toEqual(["gemini"]);
  });

  it("puts the style in the prompt", () => {
    const base = { patch: "+x", cut: false, stats: [{ path: "a.txt", status: "modified" as const, additions: 1, deletions: 0 }], subjects: ["Tweak a.txt"] };
    expect(g.commitPrompt(base)).toContain("- Tweak a.txt");
    expect(g.commitPrompt({ ...base, style: "repo" })).toContain("Match the style of this repository");
    const conventional = g.commitPrompt({ ...base, style: "conventional" });
    expect(conventional).toMatch(/Conventional Commits/);
    expect(conventional).not.toContain("- Tweak a.txt");
    expect(g.commitPrompt({ ...base, style: "plain" })).toMatch(/plain sentence/);
  });

  it("asks only the chosen agent, with the chosen style", async () => {
    agentsFrom("claude", "codex");
    fake("claude", `cat > /dev/null\necho claude > '${logs}/claude.ran'\necho 'Wrong agent'`);
    fake("codex", `cat > '${logs}/codex.stdin'\nwhile [ $# -gt 0 ]; do\n  if [ "$1" = "--output-last-message" ]; then shift; printf 'feat: tidy a.txt\\n' > "$1"; fi\n  shift\ndone`);
    store({ commitMessageAgent: "codex", commitMessageStyle: "conventional" });
    /* a different size, so git's stat check sees the edit even within the same second as the commit */
    fs.writeFileSync(path.join(repo, "a.txt"), "one\ntwo\n");
    expect(await g.suggestCommitMessage(repo)).toMatchObject({ message: "feat: tidy a.txt", source: "codex" });
    expect(fs.existsSync(path.join(logs, "claude.ran"))).toBe(false);
    expect(fs.readFileSync(path.join(logs, "codex.stdin"), "utf8")).toMatch(/Conventional Commits/);
  });

  it("asks no agent when it's off", async () => {
    agentsFrom("claude");
    fake("claude", `cat > /dev/null\necho claude > '${logs}/claude.ran'\necho 'Nope'`);
    store({ commitMessageAgent: "off" });
    fs.writeFileSync(path.join(repo, "a.txt"), "one\nthree\n");
    expect(await g.suggestCommitMessage(repo)).toMatchObject({ source: "summary", message: "Update a.txt" });
    expect(fs.existsSync(path.join(logs, "claude.ran"))).toBe(false);
  });
});
